/**
 * esbuild.config.mjs
 * Bundler configuration for the AI Proposals Obsidian Plugin.
 *
 * Targets:
 *   - Production bundle: dist/main.js
 *   - Distribution assets: dist/manifest.json, dist/styles.css
 *   - Externals: obsidian, electron, @codemirror/*, @lezer/*, node built-ins
 */

import esbuild from "esbuild";
import process from "node:process";
import fs from "node:fs";
import path from "node:path";
import { builtinModules } from "node:module";

// Determine build mode
const prod = process.argv[2] === "production";

/**
 * Copies manifest.json and styles.css to ./dist/ directory.
 */
function syncDistAssets() {
  fs.mkdirSync("dist", { recursive: true });

  // 1. Required manifest.json
  if (fs.existsSync("manifest.json")) {
    fs.copyFileSync("manifest.json", path.join("dist", "manifest.json"));
    console.log("[esbuild] Synced: manifest.json -> dist/manifest.json");
  } else {
    console.warn("[esbuild] ⚠️ Warning: manifest.json not found in project root!");
  }

  // 2. Optional / UI styling styles.css
  if (fs.existsSync("styles.css")) {
    fs.copyFileSync("styles.css", path.join("dist", "styles.css"));
    console.log("[esbuild] Synced: styles.css -> dist/styles.css");
  }
}

/**
 * Esbuild plugin to trigger static asset sync on every build completion.
 */
const copyDistAssetsPlugin = {
  name: "copy-dist-assets",
  setup(build) {
    build.onEnd((result) => {
      if (result.errors.length === 0) {
        syncDistAssets();
      }
    });
  },
};

// Top banner for generated bundle
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
AI Proposals Obsidian Plugin (ID: ai-proposals)
*/
`;

// Build context configuration
const context = await esbuild.context({
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/*",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/*",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
    ...builtinModules.map((m) => `node:${m}`),
  ],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "dist/main.js",
  banner: {
    js: banner,
  },
  plugins: [copyDistAssetsPlugin],
});

if (prod) {
  try {
    await context.rebuild();
    console.log("✓ Production build completed successfully.");
  } catch (error) {
    console.error("✗ Production build failed:", error);
    process.exit(1);
  } finally {
    await context.dispose();
  }
  process.exit(0);
} else {
  // Initial sync before watching
  syncDistAssets();

  // Watch manifest.json and styles.css for changes in dev mode
  for (const staticFile of ["manifest.json", "styles.css"]) {
    if (fs.existsSync(staticFile)) {
      try {
        fs.watch(staticFile, (eventType) => {
          if (eventType === "change" || eventType === "rename") {
            try {
              if (fs.existsSync(staticFile)) {
                fs.copyFileSync(staticFile, path.join("dist", staticFile));
                console.log(`[esbuild] Static asset updated: ${staticFile} -> dist/${staticFile}`);
              }
            } catch {
              // Ignore transient file lock
            }
          }
        });
      } catch (err) {
        console.warn(`[esbuild] Could not watch ${staticFile}:`, err.message);
      }
    }
  }

  await context.watch();
  console.log("✓ Watching for changes in src/ and static assets...");
}
